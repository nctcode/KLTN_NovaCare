// The existing question bank is the authoring source; both builds use a versioned snapshot.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const ts = require('typescript');
const root = path.resolve(__dirname, '../..');
function load(relative) {
  const source = fs.readFileSync(path.join(root, relative), 'utf8');
  const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
  const target = { exports: {} };
  new Function('exports', 'module', compiled)(target.exports, target);
  return target.exports;
}
const questions = load('nova-care-web/src/config/screening/questionBank.ts').QUESTION_BANK;
const regions = load('nova-care-web/src/constants/bodyRegions.ts').ALL_BODY_REGIONS;
if (!Array.isArray(questions) || !Array.isArray(regions)) throw new Error('Invalid screening catalog');
const version = crypto.createHash('sha256').update(JSON.stringify({ questions, regions })).digest('hex').slice(0, 16);
fs.writeFileSync(path.join(root, 'nova-care-backend/src/modules/pre-exam-v2/config/screening-catalog.json'), JSON.stringify({ version, questions, regions }, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'nova-care-web/src/config/screening/catalogVersion.ts'), `// Generated by scripts/sync-screening-catalog.cjs\nexport const SCREENING_CATALOG_VERSION = '${version}';\n`);
console.log(`Screening catalog ${version}: ${questions.length} questions, ${regions.length} regions`);
